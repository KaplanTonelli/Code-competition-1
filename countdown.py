def main() -> None:

  # input
  n:int=int(input(""))
  m:float=n
  # processing
  for i in range(n):
    if m==m:
      print(m)
      m-=1
    else:
      m-=1
      print(m)


  
  # output


if __name__ == "__main__":
  main()
    
